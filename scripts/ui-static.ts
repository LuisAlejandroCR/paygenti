// scripts/ui-static.ts: writes docs/ui/screens.html — the main screens' real rendered markup plus
// web/src/styles.css inlined, as one static file that opens with no build, server or JS framework.
// Needs a running mock server (UI_BASE_URL, default http://localhost:8796). Run: npx tsx scripts/ui-static.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { chromium, type Page } from "@playwright/test";

const ROOT = resolve(import.meta.dirname, "..");
const BASE = (process.env.UI_BASE_URL ?? "http://localhost:8796").replace(/\/+$/, "");
const OUT = resolve(ROOT, "docs/ui/screens.html");
const TERMINAL = "rosa-01";
const PIN = "1234";

async function api<T>(path: string, body?: unknown, token?: string): Promise<T> {
  const res = await fetch(`${BASE}${path}`, {
    method: body === undefined ? "GET" : "POST",
    headers: {
      ...(body !== undefined && { "Content-Type": "application/json" }),
      ...(token && { Authorization: `Bearer ${token}` }),
    },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  if (!res.ok) throw new Error(`${path} → ${res.status}`);
  return (await res.json()) as T;
}

interface Screen {
  id: string;
  title: string;
  path: string;
  /** "device": vendor phone unlocked; "office": back-office session; "none": signed out. */
  auth: "none" | "device" | "office";
}

async function capture(page: Page): Promise<string> {
  await page.waitForTimeout(1200);
  return page.evaluate(async () => {
    const app = document.getElementById("app");
    if (!app) return "";
    const copy = app.cloneNode(true) as HTMLElement;
    // Images (the QR) are inlined as data URLs so the file needs no server.
    for (const img of copy.querySelectorAll("img")) {
      const blob = await (await fetch(img.src)).blob();
      img.src = await new Promise<string>((ok) => {
        const r = new FileReader();
        r.onload = () => ok(String(r.result));
        r.readAsDataURL(blob);
      });
    }
    return copy.innerHTML;
  });
}

async function main() {
  const { token: device } = await api<{ token: string }>(`/api/terminals/${TERMINAL}/unlock`, {
    pin: PIN,
  });
  const { token: office } = await api<{ token: string }>("/api/backoffice/session", { pin: PIN });
  const open = await api<{ openSale: { id: string } | null }>(`/api/terminals/${TERMINAL}`);
  if (open.openSale) await api(`/api/sales/${open.openSale.id}/cancel`, {}, device);
  const browser = await chromium.launch();
  const sections: string[] = [];
  const shoot = async (s: Screen) => {
    const ctx = await browser.newContext({
      viewport: { width: 390, height: 844 },
      locale: "es-MX",
    });
    await ctx.addInitScript(
      ([d, o, auth]) => {
        localStorage.setItem("paygent.locale", "es");
        if (auth === "device") localStorage.setItem("paygent.device.rosa-01", d);
        if (auth === "office") sessionStorage.setItem("paygent.bo.token", o);
      },
      [device, office, s.auth] as const,
    );
    const page = await ctx.newPage();
    await page.goto(`${BASE}${s.path}`);
    const html = await capture(page);
    await ctx.close();
    sections.push(
      `<section class="ui-screen" id="${s.id}" aria-labelledby="${s.id}-h">\n` +
        `<p class="ui-label" id="${s.id}-h">${s.title} · <code>${s.path}</code></p>\n${html}\n</section>`,
    );
  };
  await shoot({ id: "unlock", title: "Desbloqueo del vendedor (PIN)", path: "/", auth: "none" });
  await shoot({ id: "entry", title: "Vendedor: nueva venta", path: "/", auth: "device" });
  const { sale } = await api<{ sale: { id: string } }>(
    `/api/terminals/${TERMINAL}/sales`,
    { amount: 12550 },
    device,
  );
  await shoot({ id: "waiting", title: "Vendedor: venta abierta (QR)", path: "/", auth: "device" });
  await shoot({ id: "checkout", title: "Cliente: pagar", path: `/pay/${sale.id}`, auth: "none" });
  await api(`/api/sales/${sale.id}/cancel`, {}, device);
  await shoot({ id: "bo-login", title: "Mi negocio: entrar", path: "/backoffice", auth: "none" });
  await shoot({ id: "backoffice", title: "Mi negocio", path: "/backoffice", auth: "office" });
  await shoot({ id: "setup", title: "Ajustes del puesto", path: "/setup", auth: "none" });
  await browser.close();

  const css = readFileSync(resolve(ROOT, "web/src/styles.css"), "utf8");
  const nav = ["unlock", "entry", "waiting", "checkout", "bo-login", "backoffice", "setup"]
    .map((id) => `<a href="#${id}">${id}</a>`)
    .join("");
  const page = `<!doctype html>
<!-- docs/ui/screens.html: GENERATED by scripts/ui-static.ts — do not edit by hand. The paygent web
     screens as static HTML (real Preact output) with web/src/styles.css inlined; no build, no JS
     framework. The source of truth stays in web/src; this is a snapshot for review and Artifacts. -->
<html lang="es">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>paygent screens</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,500;12..96,700;12..96,800&family=Inter:wght@400;500;600&display=swap" />
<style>
${css}
/* ---------- Snapshot page only ---------- */
.ui-top { position: sticky; top: 0; z-index: 10; display: flex; flex-wrap: wrap; gap: 8px; align-items: center;
  padding: 8px 16px; background: var(--surface); border-bottom: 1px solid var(--border); }
.ui-top a, .ui-top button { display: inline-flex; align-items: center; min-height: 44px; padding: 0 12px;
  border: 1px solid var(--border); border-radius: var(--radius-sm); background: var(--background);
  color: var(--foreground); font: inherit; font-size: 0.9rem; text-decoration: none; cursor: pointer; }
.ui-screen { border-bottom: 4px solid var(--border); padding-bottom: 24px; scroll-margin-top: 64px; }
.ui-label { max-width: 560px; margin: 16px auto 0; padding: 0 16px; font-weight: 700; color: var(--muted-foreground); }
</style>
</head>
<body>
<nav class="ui-top" aria-label="Pantallas">${nav}
<button type="button" aria-pressed="false" onclick="var on=this.getAttribute('aria-pressed')!=='true';this.setAttribute('aria-pressed',on);on?document.documentElement.dataset.contrast='high':delete document.documentElement.dataset.contrast">Alto contraste</button>
</nav>
${sections.join("\n")}
</body>
</html>
`;
  mkdirSync(resolve(ROOT, "docs/ui"), { recursive: true });
  writeFileSync(OUT, page);
  console.log(`wrote ${OUT} (${Math.round(page.length / 1024)} KB)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
