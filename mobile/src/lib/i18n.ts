export const DICTIONARIES: Readonly<Record<Locale, Dict>> = { en, es };

/** "es", "es-MX", "es_419" -> es; anything else (or nothing) -> en. */
export function detectLocale(tag: string | null | undefined): Locale {
  return tag && /^es(?:$|[-_])/i.test(tag) ? "es" : "en";
}

export function translate(
  locale: Locale,
  key: Key,
  params?: Record<string, string | number>,
): string {
  const text = DICTIONARIES[locale][key] ?? en[key];
  return params ? text.replace(/\{(\w+)\}/g, (m, k: string) => String(params[k] ?? m)) : text;
}

/** BCP-47 tag for speech recognition and text-to-speech. */
export function speechLang(locale: Locale): string {
  return locale === "es" ? "es-MX" : "en-US";
}
